import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { finishSceneTransition } from './scene-transition.mjs';

const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.clock.install();
  await page.goto(new URL('../index.html', import.meta.url).href);
  await page.locator('#menu-start').click();
  await page.locator('#opening-skip').click();
  await page.clock.pauseAt(new Date(Date.now() + 1000));
  await page.clock.runFor(100);
  await page.keyboard.press('p');
  assert(await page.locator('[data-phone-app="solar"]').isHidden());
  await page.evaluate(() => openPhoneApp('solar'));
  assert.equal(await page.evaluate(() => currentPhoneApp), null, 'An uninstalled app cannot open');
  await page.keyboard.press('Escape');
  await page.keyboard.press('e');
  await finishSceneTransition(page);
  await page.locator('[data-computer-app="browser"]').click();
  assert.equal(await page.locator('[data-computer-app="browser"]').textContent(), '블로그');
  assert.equal(await page.locator('#computer-window-title').textContent(), '블로그');
  assert.equal(await page.locator('#computer-internet-connect').count(), 0, 'The blog needs no connect button');
  assert(await page.locator('#computer-solar-page').isHidden());
  await page.locator('#computer-solar-download').dispatchEvent('click');
  assert.equal(await page.evaluate(() => collectedItems.has('solar-app-downloaded')), false);
  await page.evaluate(() => { solarEnabled = true; solarPoweredFloors = [17]; updatePowerState(); });
  assert(await page.locator('#computer-solar-page').isVisible(), 'Restoring power opens the blog automatically');
  await page.locator('[data-computer-app="browser"]').click();
  assert.match(await page.locator('.blog-service-bar').textContent(), /NAVER.*blog/);
  assert.match(await page.locator('#solar-blog-title').textContent(), /태양광.*다운로드/);
  assert.match(await page.locator('.blog-attachment').textContent(), /ARCHI_태양광_제어앱\.apk/);
  assert(await page.locator('#solar-blog-title').evaluate(el => el === document.activeElement), 'Opening the blog focuses the post');
  assert.equal(await page.locator('#computer-browser #computer-solar-transfer').count(), 0, 'Transfer is in its own app');
  for (const [width, height] of [[1280, 720], [390, 844], [844, 390], [568, 320]]) {
    await page.setViewportSize({ width, height });
    assert(await page.locator('#computer-browser').evaluate(el => el.scrollWidth <= el.clientWidth + 1), 'The blog does not overflow horizontally');
    await page.locator('#computer-browser').evaluate(el => { el.scrollTop = 0; });
    await page.screenshot({ path: `.local/solar-blog-home-${width}.png` });
    await page.locator('#computer-solar-download').scrollIntoViewIfNeeded();
    const download = await page.locator('#computer-solar-download').boundingBox();
    assert(download.width >= 44 && download.height >= 44 && download.x >= 0 && download.x + download.width <= width,
      'The attachment download fits desktop, portrait and landscape');
    await page.screenshot({ path: `.local/solar-blog-${width}.png` });
  }
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.locator('[data-computer-app="transfer"]').click();
  assert(await page.locator('#computer-transfer').isVisible());
  assert.equal(await page.locator('#computer-window-title').textContent(), '파일 전송');
  assert(await page.locator('#computer-solar-transfer').isDisabled());
  await page.locator('#computer-solar-transfer').dispatchEvent('click');
  assert.equal(await page.evaluate(() => computerSolarTask), null, 'A missing download cannot be transferred');
  await page.locator('[data-computer-app="browser"]').click();
  await page.locator('#computer-solar-download').click();
  assert.equal(await page.evaluate(() => collectedItems.has('solar-app-downloaded')), false, 'Download is not instant');
  assert(await page.locator('#computer-solar-download').isDisabled());
  const downloadStarted = await page.evaluate(() => computerSolarTask.started);
  await page.locator('#computer-solar-download').dispatchEvent('click');
  assert.equal(await page.evaluate(() => computerSolarTask.started), downloadStarted, 'Repeated clicks do not restart a download');
  await page.clock.runFor(2000);
  assert.equal(await page.locator('#computer-solar-download-progress').evaluate(el => el.value), 40);
  assert(!(await page.evaluate(() => progressSnapshot())).items.includes('solar-app-downloaded'), 'Incomplete downloads are not saved');
  await page.evaluate(() => { solarEnabled = false; updatePowerState(); });
  await page.clock.runFor(6000);
  assert.equal(await page.evaluate(() => collectedItems.has('solar-app-downloaded')), false, 'Power loss cancels the download');
  assert.equal(await page.evaluate(() => computerSolarTask), null);
  await page.evaluate(() => { solarEnabled = true; updatePowerState(); });
  await page.locator('#computer-solar-download').click();
  await page.locator('.computer-shortcuts [data-computer-app="files"]').click();
  await page.clock.runFor(4900);
  assert.equal(await page.evaluate(() => collectedItems.has('solar-app-downloaded')), false);
  await page.clock.runFor(100);
  assert.equal(await page.evaluate(() => collectedItems.has('solar-app-downloaded')), true, 'Download completes after five seconds while switching apps');
  assert((await page.evaluate(() => progressSnapshot())).items.includes('solar-app-downloaded'));
  await page.locator('[data-computer-app="transfer"]').click();
  await page.evaluate(() => { phoneBattery = 0; refreshSolarDownload(); });
  assert(await page.locator('#computer-solar-transfer').isDisabled());
  await page.locator('#computer-solar-transfer').dispatchEvent('click');
  assert.equal(await page.evaluate(() => collectedItems.has('solar-app-installed')), false);
  await page.evaluate(() => { phoneBattery = 100; phoneDock = { floor: 17, x: 0 }; refreshSolarDownload(); });
  assert(await page.locator('#computer-solar-transfer').isDisabled());
  await page.locator('#computer-solar-transfer').dispatchEvent('click');
  assert.equal(await page.evaluate(() => computerSolarTask), null, 'A docked phone cannot receive a transfer');
  await page.evaluate(() => { phoneDock = null; refreshSolarDownload(); });
  for (const [width, height] of [[1280, 720], [390, 844], [844, 390], [568, 320]]) {
    await page.setViewportSize({ width, height });
    assert(await page.locator('#computer-transfer').evaluate(el => el.scrollWidth <= el.clientWidth + 1), 'The transfer app fits all viewports');
    await page.locator('#computer-solar-transfer').scrollIntoViewIfNeeded();
    const transfer = await page.locator('#computer-solar-transfer').boundingBox();
    assert(transfer.width >= 44 && transfer.height >= 44 && transfer.x >= 0 && transfer.x + transfer.width <= width);
    await page.screenshot({ path: `.local/solar-transfer-${width}.png` });
  }
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.locator('#computer-solar-transfer').click();
  assert.equal(await page.evaluate(() => collectedItems.has('solar-app-installed')), false, 'Transfer is not instant');
  assert(await page.locator('[data-phone-app="solar"]').isHidden());
  await page.clock.runFor(3000);
  assert.equal(await page.locator('#computer-solar-transfer-progress').evaluate(el => el.value), 37);
  await page.screenshot({ path: '.local/solar-transfer-progress.png' });
  assert(!(await page.evaluate(() => progressSnapshot())).items.includes('solar-app-installed'), 'Incomplete transfers are not saved');
  await page.evaluate(() => { phoneBattery = 0; refreshSolarDownload(); });
  await page.clock.runFor(8000);
  assert.equal(await page.evaluate(() => collectedItems.has('solar-app-installed')), false, 'An unavailable phone cancels the transfer');
  await page.evaluate(() => { phoneBattery = 100; refreshSolarDownload(); });
  await page.locator('#computer-solar-transfer').click();
  await page.clock.runFor(7900);
  await page.locator('#computer-exit').click();
  await finishSceneTransition(page);
  await page.clock.runFor(8000);
  assert.equal(await page.evaluate(() => collectedItems.has('solar-app-installed')), false, 'Leaving just before completion cancels the transfer during the exit fade');
  await page.keyboard.press('e');
  await finishSceneTransition(page);
  await page.locator('[data-computer-app="transfer"]').click();
  await page.locator('#computer-solar-transfer').click();
  await page.clock.runFor(7900);
  assert.equal(await page.evaluate(() => collectedItems.has('solar-app-installed')), false);
  await page.clock.runFor(100);
  assert.equal(await page.evaluate(() => collectedItems.has('solar-app-installed')), true);
  assert.equal(await page.evaluate(() => computerSolarTask), null);
  assert(await page.locator('#computer-solar-transfer').isDisabled());
  assert.match(await page.locator('#computer-transfer-status').textContent(), /등록 완료/);
  await page.keyboard.press('Escape');
  await page.keyboard.press('Escape');
  await finishSceneTransition(page);
  await page.keyboard.press('p');
  await page.locator('[data-phone-app="solar"]').click();
  const supply = async floor => {
    await page.locator('#phone-solar-floor').selectOption(String(floor));
    await page.locator('#phone-solar-supply').click();
  };
  const floors = () => page.evaluate(() => [...solarPoweredFloors]);
  await supply(12);
  assert.deepEqual(await floors(), [17, 12]);
  await page.locator('#phone-solar-floor').selectOption('7');
  await page.locator('#phone-solar-supply').focus();
  for (let i = 0; i < 4; i++) await page.keyboard.down('Enter');
  await page.keyboard.up('Enter');
  assert.deepEqual(await floors(), [12, 7], 'Remote control uses the same two-floor FIFO');
  assert.match(await page.locator('#phone-solar-status').textContent(), /12F · 7F.*2\/2/);
  await supply(12);
  assert.deepEqual(await floors(), [7], 'Selecting a lit floor turns off only that floor');
  await page.evaluate(() => { phoneBattery = 0; refreshPhone(); });
  await page.locator('#phone-solar-supply').dispatchEvent('click');
  await page.locator('#phone-solar-toggle').dispatchEvent('click');
  assert.deepEqual(await floors(), [7], 'An empty phone cannot change power');
  assert.equal(await page.evaluate(() => solarEnabled), true);
  await page.evaluate(() => { phoneBattery = 100; refreshPhone(); });
  await page.locator('[data-phone-app="solar"]').click();
  await page.locator('#phone-solar-toggle').click();
  assert.deepEqual(await floors(), []);
  assert.equal(await page.evaluate(() => solarEnabled), false);
  await page.locator('#phone-solar-toggle').click();
  await supply(17);
  const saved = await page.evaluate(() => progressSnapshot());
  assert(saved.items.includes('solar-app-installed'));
  await page.evaluate(data => restoreProgress(data), saved);
  assert.deepEqual(await floors(), [17]);
  assert.equal(await page.evaluate(() => collectedItems.has('solar-app-installed')), true);
  assert.deepEqual(errors, []);
  console.log('PASS: automatic blog, separate transfer app, timed progress, duplicate guards, interrupted download/transfer, responsive layouts, remote power and saved installation.');
} finally { await browser.close(); }
