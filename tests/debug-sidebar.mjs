import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
import { finishSceneTransition } from './scene-transition.mjs';

await mkdir('.local', { recursive: true });
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.clock.install({ time: new Date('2026-10-16T00:00:00Z') });
  await page.goto(new URL('../index.html', import.meta.url).href);
  await page.clock.pauseAt(new Date('2026-10-16T00:00:01Z'));
  const sidebar = page.locator('#debug-sidebar');
  assert(await sidebar.isHidden());
  await page.locator('#menu-settings-button').click();
  await page.locator('#menu-debug-toggle').click();
  assert.equal(await page.locator('#menu-debug-toggle').getAttribute('aria-pressed'), 'true');
  assert(await sidebar.isHidden(), 'Settings can enable tools without covering the menu');
  await page.locator('#menu-settings .menu-back').click();
  await page.locator('#menu-start').click();
  assert(await sidebar.isHidden(), 'Opening hides enabled tools');
  await page.locator('#opening-skip').click();
  await page.clock.runFor(100);
  assert(await sidebar.isVisible());
  for (const id of ['debug-floor', 'debug-room', 'debug-sanity', 'debug-console']) {
    assert(await page.locator(`#${id}`).evaluate(el => el.closest('#debug-sidebar') !== null));
  }
  assert.equal(await page.locator('nav [data-direction], nav #jump').count(), 0);
  assert(await page.locator('#sanity-hud #debug-sanity').count() === 0);
  await page.keyboard.press('F2');
  assert(await sidebar.isHidden());
  await page.screenshot({ path: '.local/debug-off-desktop.png' });
  const x = await page.evaluate(() => body.position.x);
  await page.keyboard.down('a'); await page.clock.runFor(300);
  await page.keyboard.press('F2');
  const stopped = await page.evaluate(() => body.position.x);
  assert(stopped < x - 40, 'Keyboard movement remains available');
  await page.clock.runFor(300); await page.keyboard.up('a');
  assert.equal(await page.evaluate(() => body.position.x), stopped, 'Opening tools releases held movement');
  await page.locator('#debug-sanity-number').fill('24');
  await page.keyboard.press('Enter');
  assert.equal(await page.evaluate(() => sanity), 24);
  assert(await sidebar.isVisible(), 'Number entry does not submit or reload the game');
  await page.keyboard.press('a'); await page.keyboard.press('Space');
  await page.clock.runFor(200);
  assert.equal(await page.evaluate(() => body.position.x), stopped, 'Editing tools does not move the player');
  await page.locator('#debug-battery').fill('0');
  assert.equal(await page.evaluate(() => phoneBattery), 0);
  assert.equal(await page.evaluate(() => phoneLightOn), false);
  await page.locator('#debug-restore').click();
  assert.equal(await page.evaluate(() => sanity), 100);
  assert.equal(await page.evaluate(() => phoneBattery), 100);
  await page.locator('#debug-room-select').selectOption('f2-lounge');
  await page.locator('#debug-room button').click();
  await finishSceneTransition(page);
  assert.equal(await page.evaluate(() => dynamicFloorId), 'f2-lounge');
  await page.clock.runFor(50);
  assert.match(await page.locator('#debug-state').textContent(), /f2-lounge/);
  await page.locator('#debug-room-select').selectOption('office');
  await page.locator('#debug-room button').click();
  await finishSceneTransition(page);
  assert.equal(await page.evaluate(() => room), 'office');
  assert.deepEqual(await page.evaluate(() => PUZZLE_STEPS.filter(step => step.at !== 'office' && !floorById.has(step.at))), []);
  await page.locator('#debug-puzzle-select').selectOption({ label: '17F 터미널 · ARCHI-MAIN 외부 연결 로그' });
  await page.locator('#debug-puzzle button').click();
  await finishSceneTransition(page);
  assert.deepEqual(await page.evaluate(() => [currentSceneFloor, realBuildingBlackout(), solarEnabled,
    collectedItems.has('f7-training-time-solved'), collectedItems.has('f7-external-connection-solved')]), [17, true, true, true, false]);
  await page.locator('#debug-puzzle-select').selectOption({ index: 0 });
  await page.locator('#debug-puzzle button').click();
  await finishSceneTransition(page);
  assert.deepEqual(await page.evaluate(() => [room, realBuildingBlackout(), solarEnabled, [...collectedItems]]), ['office', false, false, ['f17-badge']]);
  await page.evaluate(() => triggerBuildingBlackout());
  await page.locator('#debug-floor-select').selectOption('f2');
  await page.locator('#debug-floor button').click();
  await finishSceneTransition(page);
  assert.equal(await page.evaluate(() => currentSceneFloor), 2);
  await page.locator('#debug-console-toggle').click();
  await page.locator('#debug-all-power').click();
  assert.equal(await page.evaluate(() => allPowerOverride), true);
  await page.locator('#debug-spawn-hallucination').click();
  assert(await page.evaluate(() => hallucinationMode === 'ambient'));
  await page.clock.runFor(50);
  const closeBox = await page.locator('#debug-close').boundingBox();
  assert(closeBox.y >= 0 && closeBox.y + closeBox.height <= 720, 'Sidebar close remains visible after scrolling to events');
  await page.screenshot({ path: '.local/debug-sidebar-desktop.png' });
  await page.evaluate(() => startStoryScene({ lines: ['개발 UI 숨김 확인'], flag: null }));
  assert(await sidebar.isHidden(), 'Story scenes hide the entire sidebar');
  await page.keyboard.press('Escape');
  assert(await sidebar.isVisible(), 'Tools return after the cutscene');
  await page.locator('#debug-sanity-number').focus();
  await page.keyboard.press('Escape');
  assert(await sidebar.isHidden(), 'Escape inside a field closes the sidebar');
  assert(await page.locator('#main-menu').isHidden(), 'Closing tools does not open the game menu');
  await page.keyboard.press('Space'); await page.clock.runFor(150);
  assert(await page.evaluate(() => body.bounds.max.y < floorY - 20), 'Keyboard jumping still works');
  await page.reload();
  assert(await sidebar.isHidden(), 'Every page load starts with tools hidden');
  assert.deepEqual(errors, []);
  console.log('PASS: developer mode toggle/menu/F2, sidebar grouping, keyboard isolation, room/floor travel, resources, power/events, cutscene hiding and removed arrow controls.');
} finally {
  await browser.close();
}
