import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
import { finishSceneTransition } from './scene-transition.mjs';

await mkdir('.local', { recursive: true });
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('requestfailed', request => errors.push(request.url()));
  await page.clock.install();
  await page.goto(new URL('../index.html', import.meta.url).href);
  await page.locator('#opening-skip').click();
  await page.clock.pauseAt(new Date(Date.now() + 1000));
  await page.clock.runFor(100);
  const pc = page.locator('#computer');
  const note = page.locator('#computer-note');
  const app = page.locator('#computer-window');
  const position = () => page.locator('#player').evaluate(el => el.style.transform);
  const initialPosition = await position();
  assert.equal(await page.locator('#interaction-hint').textContent(), 'E · 컴퓨터 사용');
  await page.keyboard.press('e');
  assert.equal(await page.locator('#room-transition').getAttribute('data-phase'), 'out');
  await page.clock.runFor(400);
  assert(await pc.isVisible());
  assert(await pc.evaluate(el => el.inert), 'Computer is blocked during fade-in');
  await finishSceneTransition(page);
  assert(await page.locator('#stage').evaluate(el => el.inert));
  await pc.locator('img').evaluateAll(images => Promise.all(images.filter(img => img.src).map(img => img.decode())));
  await page.screenshot({ path: '.local/computer-desktop.png' });
  await page.keyboard.down('d');
  await page.keyboard.press('Space');
  await page.clock.runFor(250);
  await page.keyboard.up('d');
  assert.equal(await position(), initialPosition, 'Desktop keyboard input cannot move the player');
  await pc.locator('.computer-shortcuts [data-computer-app="files"]').click();
  const records = pc.locator('[data-computer-document]');
  assert.equal(await records.count(), 8);
  assert.equal(await pc.locator('[data-computer-card], #computer-card').count(), 0);
  assert.equal(await pc.getByText(/사원증/).count(), 0, 'Employee badges are not available on the PC');
  await page.screenshot({ path: '.local/computer-company-files.png' });
  const documentIds = await records.evaluateAll(buttons => buttons.map(button => button.dataset.computerDocument));
  const titles = new Set();
  for (const documentId of documentIds) {
    await pc.locator(`[data-computer-document="${documentId}"]`).click();
    assert(await page.locator('#computer-document').isVisible());
    titles.add(await page.locator('#computer-document-title').textContent());
    assert((await page.locator('#computer-document-body').textContent()).length > 200);
    assert.match(await page.locator('#computer-document-meta').textContent(), /09\./);
    if (documentId === 'weekly-report') await page.screenshot({ path: '.local/computer-company-report.png' });
    await pc.getByRole('button', { name: '파일 목록으로' }).click();
  }
  assert.equal(titles.size, 8, 'Each company record opens its own contents');
  await pc.getByRole('combobox', { name: '문서 분류' }).selectOption('프로젝트');
  assert.equal(await pc.locator('[data-computer-document]:visible').count(), 3);
  await pc.getByRole('searchbox', { name: '문서 검색' }).fill('조현아');
  assert.equal(await pc.locator('[data-computer-document]:visible').count(), 2);
  await pc.getByRole('searchbox', { name: '문서 검색' }).fill('없는문서123');
  assert(await pc.locator('#computer-files-empty').isVisible());
  assert.equal(await pc.locator('#computer-file-count').textContent(), '0개 문서');
  await pc.getByRole('combobox', { name: '문서 분류' }).selectOption('');
  await pc.getByRole('searchbox', { name: '문서 검색' }).fill('fac-022');
  assert.equal(await pc.locator('[data-computer-document]:visible').count(), 1);
  await pc.getByRole('searchbox', { name: '문서 검색' }).fill('');
  await pc.locator('#computer-files [data-computer-app="notes"]').click();
  const text = 'ARCHI 업무 기록\nwasd e Shift 17층\n<문서 내용>';
  await note.fill(text);
  await page.keyboard.type(' wasd e');
  await page.keyboard.press('Space');
  await page.clock.runFor(100);
  assert.equal(await position(), initialPosition, 'Typing movement and interaction keys stays inside the editor');
  const saved = await note.inputValue();
  assert.equal(await page.locator('#computer-save-status').textContent(), '저장되지 않음');
  await pc.getByRole('button', { name: '메모 저장', exact: true }).click();
  assert.equal(await page.locator('#computer-save-status').textContent(), '저장됨');
  await page.keyboard.press('Escape');
  assert(await app.isHidden());
  assert(await pc.isVisible());
  await pc.getByRole('button', { name: '컴퓨터 사용 종료' }).focus();
  await page.keyboard.press('Tab');
  assert(await pc.locator('.computer-shortcuts button').first().evaluate(el => el === document.activeElement));
  await page.keyboard.press('Shift+Tab');
  assert(await pc.locator('#computer-exit').evaluate(el => el === document.activeElement));
  await page.keyboard.press('Escape');
  await finishSceneTransition(page);
  assert(await pc.isHidden());
  assert.equal(await page.locator('#stage').evaluate(el => el.inert), false);
  assert.equal(await position(), initialPosition);
  await page.keyboard.down('d');
  await page.clock.runFor(600);
  await page.keyboard.up('d');
  await page.clock.runFor(34);
  await page.keyboard.press('e');
  assert(await pc.isHidden(), 'A distant computer cannot be used');
  await page.reload();
  await page.locator('#opening-skip').click();
  await page.clock.runFor(100);
  await page.keyboard.press('Space');
  await page.clock.runFor(150);
  await page.keyboard.press('e');
  assert(await pc.isHidden(), 'Computer cannot be used while airborne');
  await page.clock.runFor(1200);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '상호작용', exact: true }).click();
  await finishSceneTransition(page);
  await pc.locator('.computer-shortcuts [data-computer-app="files"]').click();
  await page.screenshot({ path: '.local/computer-company-files-mobile.png' });
  await pc.locator('[data-computer-document="floor-guide"]').click();
  const documentScroll = page.locator('#computer-document-scroll');
  assert(await documentScroll.evaluate(el => el.scrollWidth <= el.clientWidth + 1), 'Document tables fit mobile width');
  await documentScroll.evaluate(el => { el.scrollTop = el.scrollHeight; });
  assert(await documentScroll.evaluate(el => el.scrollTop > 0), 'Long documents can scroll to the final section');
  await pc.getByRole('button', { name: '파일 목록으로' }).click();
  await pc.locator('[data-computer-document="organization"]').click();
  assert.equal(await documentScroll.evaluate(el => el.scrollTop), 0, 'Opening another document resets reading position');
  await page.screenshot({ path: '.local/computer-company-document-mobile.png' });
  await pc.locator('.computer-shortcuts [data-computer-app="notes"]').click();
  assert.equal(await note.inputValue(), saved, 'Saved memo survives page reload');
  await page.screenshot({ path: '.local/computer-mobile-notes.png' });
  const bounds = await app.boundingBox();
  assert(bounds.x >= 0 && bounds.x + bounds.width <= 390 && bounds.y + bounds.height <= 844);
  await page.evaluate(() => {
    Storage.prototype.setItem = () => { throw new DOMException('Unavailable', 'QuotaExceededError'); };
  });
  await note.fill('저장 실패해도 남아 있어야 할 메모');
  await pc.getByRole('button', { name: '메모 저장', exact: true }).click();
  assert.match(await page.locator('#computer-save-status').textContent(), /저장 실패/);
  await pc.getByRole('button', { name: '컴퓨터 사용 종료' }).click();
  await finishSceneTransition(page);
  await page.keyboard.press('e');
  await finishSceneTransition(page);
  await pc.locator('.computer-shortcuts [data-computer-app="notes"]').click();
  assert.equal(await note.inputValue(), '저장 실패해도 남아 있어야 할 메모');
  await page.setViewportSize({ width: 844, height: 390 });
  await page.screenshot({ path: '.local/computer-mobile-landscape.png' });
  const landscape = await app.boundingBox();
  assert(landscape.width > 200 && landscape.height > 150);
  assert.deepEqual(errors, []);
  console.log('PASS: computer proximity, fades, eight company documents, search, filters, no badges, mobile reading, memo persistence and input isolation.');
} finally {
  await browser.close();
}
