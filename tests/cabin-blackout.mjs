import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';

await mkdir('.local', { recursive: true });
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 }, hasTouch: true });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.clock.install({ time: new Date('2026-10-04T00:00:00Z') });
  await page.goto(new URL('../index.html', import.meta.url).href);
  await page.locator('#menu-start').click();
  if (await page.locator('#menu-new-confirm').isVisible()) await page.locator('#menu-new-confirm').click();
  await page.locator('#opening-skip').click();
  await page.clock.pauseAt(new Date('2026-10-04T00:01:00Z'));
  await page.locator('#cabin-art').evaluate(img => img.decode());
  await page.evaluate(() => { elevatorCars[0].floor = 17; showCabin(0); });
  const scene = page.locator('#cabin-scene');
  assert.equal(await scene.getAttribute('data-blackout'), 'false');
  await page.screenshot({ path: '.local/cabin-light-before.png' });
  await page.evaluate(() => triggerBuildingBlackout()); await page.clock.runFor(50);
  assert.equal(await scene.getAttribute('data-blackout'), 'true');
  const shade = await scene.evaluate(el => {
    const style = getComputedStyle(el, '::after');
    return { background: style.backgroundImage, pointerEvents: style.pointerEvents, z: style.zIndex };
  });
  assert.match(shade.background, /linear-gradient/); assert.equal(shade.pointerEvents, 'none');
  assert.match(await page.locator('#cabin-doorway').evaluate(el => getComputedStyle(el).backgroundImage), /floor17-off/);
  assert(await page.locator('#cabin-display').evaluate(el => Number(getComputedStyle(el).zIndex) > 1));
  await page.screenshot({ path: '.local/cabin-blackout-open.png' });
  assert(await page.locator('#cabin-floor-buttons [data-floor="16"]').isDisabled());
  await page.locator('#power-lever').dispatchEvent('click');
  await page.locator('#cabin-floor-buttons [data-floor="16"]').click();
  assert.equal(await page.locator('#cabin-floor-buttons [data-floor="16"]').getAttribute('aria-pressed'), 'true');
  await page.locator('#cabin-close').click(); await page.clock.runFor(1200);
  assert.equal(await scene.getAttribute('data-door'), 'closed');
  assert.equal(await scene.getAttribute('data-blackout'), 'true');
  await page.screenshot({ path: '.local/cabin-blackout-closed.png' });
  await page.clock.runFor(2500);
  assert.equal(await scene.getAttribute('data-floor'), '16');
  assert.equal(await scene.getAttribute('data-blackout'), 'true');
  assert(await page.locator('#cabin-exit').isEnabled());
  await page.evaluate(() => { solarEnabled = true; solarPoweredFloor = 16; updatePowerState(); refreshCabin(); });
  assert.equal(await scene.getAttribute('data-blackout'), 'true', 'Floor-only solar power does not relight the car');
  await page.evaluate(() => { elevatorCars[0].floor = 17; solarPoweredFloor = 17; refreshCabin(); });
  assert.equal(await scene.getAttribute('data-blackout'), 'true');
  assert.doesNotMatch(await page.locator('#cabin-doorway').evaluate(el => getComputedStyle(el).backgroundImage), /floor17-off/, 'Restored hallway uses lit art independently of cabin lighting');
  await page.evaluate(() => { elevatorCars[0].floor = -1; cabinStatus.textContent = 'B1 · 문 열림'; refreshCabin(); });
  assert.equal(await scene.getAttribute('data-blackout'), 'true', 'Basement floor emergency lighting does not restore cabin mains');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#cabin-open').scrollIntoViewIfNeeded();
  await page.locator('#cabin-open').tap();
  await page.screenshot({ path: '.local/cabin-blackout-mobile.png' });
  await page.locator('#cabin-exit').tap(); await page.clock.runFor(800);
  assert(await page.locator('#elevator-cabin').isHidden());
  assert.equal(await page.locator('#stage').evaluate(el => el.inert), false);
  await page.evaluate(() => showCabin(0));
  assert.equal(await scene.getAttribute('data-blackout'), 'true', 'Reboarding preserves darkness');
  await page.evaluate(() => { buildingBlackout = false; updatePowerState(); refreshCabin(); });
  assert.equal(await scene.getAttribute('data-blackout'), 'false');
  assert.equal(await scene.evaluate(el => getComputedStyle(el, '::after').content), 'none');
  assert.deepEqual(errors, []);
  console.log('PASS: lit-to-dark cabin, open/closed doors, selected controls, travel/arrival, solar/basement boundaries, touch exit, reboarding and mains restoration.');
} finally { await browser.close(); }
