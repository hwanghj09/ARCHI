import assert from 'node:assert/strict';
import { mkdir, readFile, readdir } from 'node:fs/promises';
import { chromium } from 'playwright';

assert(!(await readdir('.')).some(file => file.endsWith('.css')), 'Styles live in css/');
const html = await readFile('index.html', 'utf8');
assert(!html.includes('<style>'), 'The main game stylesheet is external too');
assert([...html.matchAll(/rel="stylesheet" href="([^"]+)"/g)].every(match => match[1].startsWith('css/')));
await mkdir('.local', { recursive: true });
const browser = await chromium.launch();
try {
  for (const [name, width, height] of [['desktop', 1280, 720], ['portrait', 390, 844], ['landscape', 844, 390]]) {
    const page = await browser.newPage({ viewport: { width, height }, hasTouch: true });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('response', response => { if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`); });
    await page.clock.install({ time: new Date('2026-10-11T00:00:00Z') });
    await page.goto(new URL('../index.html', import.meta.url).href);
    await page.clock.pauseAt(new Date('2026-10-11T00:01:00Z'));
    await page.locator('#menu-start').click();
    await page.locator('#opening-skip').click();
    await page.evaluate(() => {
      window.nightEvents = []; window.nightStops = [];
      const play = playGameSound, stop = stopGameSound;
      playGameSound = (name, options) => { nightEvents.push(name); play(name, options); };
      stopGameSound = name => { nightStops.push(name); stop(name); };
    });
    await page.clock.runFor(900);
    assert(await page.evaluate(() => officeComputer.element.dataset.echo === 'true' && officeComputer.element.dataset.power === 'off'));
    assert.match(await page.locator('#office-computer').evaluate(el => getComputedStyle(el, '::after').content), /ARCHK/);
    assert.match(await page.locator('#interaction-status').textContent(), /외부 연결 시도/);
    assert(await page.locator('#first-night-shade').isVisible());
    assert(await page.locator('#darkness').isHidden(), 'Partial night lighting does not cut mains power');
    await page.screenshot({ path: `.local/first-night-office-${name}.png` });
    const beforePhone = await page.evaluate(() => firstNightCue.remaining);
    await page.keyboard.press('p'); await page.clock.runFor(700);
    assert.equal(await page.evaluate(() => firstNightCue.remaining), beforePhone, 'Phone use pauses the scripted cue');
    await page.keyboard.press('Escape'); await page.clock.runFor(3000);
    assert.equal(await page.locator('#office-computer').getAttribute('data-echo'), null);
    const walkTo = async x => {
      const from = await page.evaluate(() => body.position.x);
      const key = x >= from ? 'd' : 'a';
      await page.locator('#stage').focus(); await page.keyboard.down(key);
      await page.clock.runFor(Math.abs(x - from) / 200 * 1000);
      await page.keyboard.up(key); await page.clock.runFor(50);
    };
    await walkTo(965); await page.keyboard.press('e'); await page.clock.runFor(850);
    assert.equal(await page.locator('#world').getAttribute('data-room'), 'corridor');
    await page.clock.runFor(750);
    assert.match(await page.locator('#interaction-status').textContent(), /잠금장치/);
    await walkTo(1170);
    assert(await page.evaluate(() => collectedItems.has('first-night-relays') && collectedItems.has('first-night-stopped')));
    assert.match(await page.locator('#interaction-status').textContent(), /내 움직임에 반응/);
    assert(await page.evaluate(() => nightStops.includes('night-relay')), 'Standing stops the remote mechanical sequence');
    await walkTo(1450);
    assert(await page.locator('#first-night-cctv').isVisible());
    const tracked = await page.locator('#first-night-cctv').evaluate(el => getComputedStyle(el).clipPath);
    await walkTo(1550);
    assert.notEqual(await page.locator('#first-night-cctv').evaluate(el => getComputedStyle(el).clipPath), tracked, 'The surveillance direction follows the player');
    await page.screenshot({ path: `.local/first-night-corridor-${name}.png` });
    await page.evaluate(() => { saveProgress(); window.nightSave = readProgress(); restoreProgress(nightSave); });
    await page.clock.runFor(500);
    assert(await page.locator('#first-night-cctv').isVisible(), 'Surveillance survives saved progress');
    assert.equal(await page.locator('#office-computer').getAttribute('data-echo'), null);
    await page.evaluate(() => { nightEvents.length = 0; });
    await walkTo(1840);
    assert(await page.evaluate(() => blackoutSceneActive));
    const advance = async elapsed => {
      const current = await page.evaluate(() => blackoutElapsed);
      await page.clock.runFor(Math.max(0, elapsed - current) + 34);
    };
    await advance(4200);
    assert(await page.evaluate(() => buildingBlackout && gameAudioAmbience.size === 0), 'Mains cut kills the ventilation loop');
    await advance(5000);
    assert.equal(await page.locator('#world').getAttribute('data-blackout-scene'), 'listen');
    assert.match(await page.locator('#blackout-caption').textContent(), /엘리베이터 잠금장치/);
    await advance(6600);
    assert(await page.locator('#blackout-terminal').isVisible());
    assert.equal(await page.locator('#blackout-terminal').textContent(), '정수호');
    assert(await page.locator('.elevator-indicator').evaluateAll(elements => elements.every(el => Number(getComputedStyle(el).opacity) <= .1)), 'Only the anomalous name remains bright');
    assert.equal(await page.locator('#first-night-shade').isVisible(), false);
    await page.screenshot({ path: `.local/first-night-blackout-${name}.png` });
    const events = await page.evaluate(() => [...nightEvents]);
    assert.equal(events.filter(event => event === 'blackout').length, 1);
    assert.equal(events.filter(event => event === 'night-lock').length, 1);
    assert.equal(events.filter(event => event === 'night-static').length, 1);
    assert(!events.includes('night-knock') && !events.includes('night-step'));
    await advance(8350);
    assert(await page.evaluate(() => !blackoutSceneActive && !stage.inert && buildingBlackout));
    assert(await page.locator('#blackout-terminal').isHidden());
    await page.keyboard.press('f'); await page.clock.runFor(100);
    assert.equal(await page.locator('#world').getAttribute('data-flashlight'), 'on');
    await page.evaluate(() => { solarEnabled = true; solarPoweredFloors = [17]; updatePowerState(); render(); });
    assert(await page.locator('#first-night-shade').isHidden(), 'Restoring power does not replay the introductory night');
    await page.evaluate(() => performFloorChange('f16'));
    assert(await page.locator('#first-night-cctv').isHidden(), 'Surveillance art stays on 17F');
    await page.evaluate(() => { startNewGame(); finishOpening(); });
    await page.clock.runFor(900);
    assert(await page.evaluate(() => officeComputer.element.dataset.echo === 'true'), 'New game resets the one-time events');
    assert.deepEqual(errors, [], `${name}: scripts, relocated styles and assets load`);
    await page.close();
  }
  console.log('PASS: external CSS, monitor intrusion, door control, movement-sensitive relays, CCTV tracking, saved events, silence/lock/name blackout, handoff, flashlight, power recovery, new game, desktop and mobile');
} finally { await browser.close(); }
